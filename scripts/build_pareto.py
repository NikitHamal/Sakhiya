#!/usr/bin/env python3
"""Build docs/pareto.json from MEASURED artifacts only (eval/forensic_*.json + docs/models_*/size.json).
No hand-typed quality numbers: the web Pareto chart renders exactly this file."""
import json, os, sys
R = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
def rj(p):
    try: return json.load(open(os.path.join(R, p)))
    except Exception: return {}
TIERS = [
    ("v6_sano_1p5m", "Sakhiya-Sano", "docs/models_sano/size.json", "eval/forensic_v6_sano_1p5m.json", 4.0),
    ("v6_voca_4m", "Sakhiya-Voca", "docs/models_voca/size.json", "eval/forensic_v6_voca_4m.json", 3.85),
    ("v6_teacher", "Sakhiya v6 Teacher (browser build)", "docs/models_v2/size.json", "eval/forensic_v6_teacher.json", 4.0),
]
rows = []
for tag, label, sz, fj, target in TIERS:
    f7 = rj(fj.replace("forensic_v6_voca_4m", "forensic_v7_voca").replace("forensic_v6_sano_1p5m", "forensic_v7_sano")) if "teacher" not in fj else {}
    s, f = rj(sz), (f7 or rj(fj)); b = (s.get("browser_ort_node") or {})
    t = b.get("tiny") or {}; h = b.get("fp16") or {}
    rows.append(dict(tag=tag, label=label, params_m=round((s.get("params_total") or 0) / 1e6, 2),
        int8_mb=s.get("total_tiny_mb"), fp16_mb=s.get("total_fp16_mb"),
        rtf_int8=t.get("rtf_1thread"), rtf_fp16=h.get("rtf_1thread"),
        utmos_15=f.get("utmos_15"), word_drops=f.get("word_drop_count"), stutters=f.get("stutter_count"),
        clicks=f.get("clicks"), f0_shutters=f.get("f0_shutters"), sv_cos=f.get("sv_cos_ne_sa"),
        utmos_target=target, meets_quality=bool((f.get("utmos_15") or 0) >= target and not f.get("word_drop_count"))))
b5 = rj("eval/forensic_v5_c1.json")
rows.append(dict(tag="v5_c1", label="v5_c1 baseline (previous release)", params_m=15.23, int8_mb=15.99, fp16_mb=31.03,
    rtf_int8=0.1884, rtf_fp16=0.1666, utmos_15=b5.get("utmos_15"), word_drops=b5.get("word_drop_count"),
    stutters=b5.get("stutter_count"), clicks=b5.get("clicks"), f0_shutters=b5.get("f0_shutters"),
    sv_cos=b5.get("sv_cos_ne_sa"), utmos_target=3.85, meets_quality=True))
json.dump(dict(note="All numbers measured by scripts/forensic_audio_gate.py (UTMOS22 over the 15 master clips) and ORT-node size.json. Generated by scripts/build_pareto.py.", tiers=rows),
          open(os.path.join(R, "docs/pareto.json"), "w"), indent=1, ensure_ascii=False)
T = rj("docs/tiers.json"); m = {"voca": "v6_voca_4m", "sano": "v6_sano_1p5m", "int8": "v6_teacher", "fp16": "v6_teacher"}
by = {r["tag"]: r for r in rows}
for t in T.get("tiers", []):
    p = by[m[t["id"]]]; i8 = t["prec"] == "int8"
    t.update(mb=p["int8_mb"] if i8 else p["fp16_mb"], rtf=p["rtf_int8"] if i8 else p["rtf_fp16"], utmos=p["utmos_15"])
    t["desc"] = {"voca": "Experimental 4.4 MB student", "sano": "Experimental 1.8 MB student", "int8": "v6 teacher build (QDQ int8)", "fp16": "v6 teacher build (fp16)"}[t["id"]] + f" · measured UTMOS {p['utmos_15']:.2f}" + ("" if p["meets_quality"] else " · QUALITY BELOW TARGET (still training)")
json.dump(T, open(os.path.join(R, "docs/tiers.json"), "w"), indent=1, ensure_ascii=False)
for r in rows: print(r["tag"], r["int8_mb"], r["rtf_int8"], r["utmos_15"], r["word_drops"], r["meets_quality"])
